import React, { useState } from 'react';
import { X, Copy, Check, Download, FileText } from 'lucide-react';
import type { AnalyzedPlan } from '../types';

interface PRMarkdownModalProps {
  plan: AnalyzedPlan;
  onClose: () => void;
}

export const PRMarkdownModal: React.FC<PRMarkdownModalProps> = ({ plan, onClose }) => {
  const [copied, setCopied] = useState(false);

  const generateMarkdown = () => {
    let statusBadge = "✅ SAFE TO APPLY";
    if (plan.stats.critical_alerts_count > 0) {
      statusBadge = "🚨 CRITICAL DESTRUCTION RISK";
    } else if (plan.stats.replace_count > 0 || plan.stats.delete_count > 0) {
      statusBadge = "⚠️ DESTRUCTIVE CHANGES DETECTED";
    } else if (plan.stats.security_issues_count > 0) {
      statusBadge = "🛡️ SECURITY VIOLATIONS FOUND";
    }

    let md = `## TofuForge Plan Analysis Summary\n\n`;
    md += `**Status:** \`${statusBadge}\`\n\n`;
    md += `| Metric | Count | Details |\n`;
    md += `| :--- | :--- | :--- |\n`;
    md += `| **Resources to Create** | \`+${plan.stats.create_count}\` | New resources added |\n`;
    md += `| **Resources to Update** | \`~${plan.stats.update_count}\` | In-place attribute changes |\n`;
    md += `| **Resources to Delete** | \`-${plan.stats.delete_count}\` | Permanent deletions |\n`;
    md += `| **Resources to Replace** | \`±${plan.stats.replace_count}\` | Destroy and recreate cycles |\n`;
    md += `| **Total Blast Radius Score** | \`${plan.stats.total_blast_radius}\` | Cumulative downstream risk |\n`;
    md += `| **Critical Destruction Alerts** | \`${plan.stats.critical_alerts_count}\` | Stateful or cascading risks |\n`;
    md += `| **Security Findings** | \`${plan.stats.security_issues_count}\` | Pre-flight policy violations |\n\n`;

    if (plan.destruction_alerts && plan.destruction_alerts.length > 0) {
      md += `### ⚠️ Destruction & Replacement Guard\n\n`;
      md += `The following resources undergo deletion or replacement. Stateful resources or those with downstream dependencies require explicit verification:\n\n`;
      md += `| Severity | Action | Resource Address | Type | Blast Radius | Downstream | Replacement Triggers |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;

      plan.destruction_alerts.forEach(a => {
        const sevIcon = a.severity === 'CRITICAL' ? '🔴' : a.severity === 'HIGH' ? '🟠' : '🟡';
        const actStr = a.action === 'replace' ? 'DESTROY & RECREATE' : a.action.toUpperCase();
        const triggers = a.replacement_keys && a.replacement_keys.length > 0 ? a.replacement_keys.join(', ') : 'n/a';
        md += `| ${sevIcon} **${a.severity}** | \`${actStr}\` | \`${a.resource_address}\` | \`${a.resource_type}\` | \`${a.blast_radius}\` | \`${a.downstream_count}\` | \`${triggers}\` |\n`;
      });
      md += `\n`;
    }

    if (plan.security_findings && plan.security_findings.length > 0) {
      md += `### 🛡️ Pre-Flight Security Audit\n\n`;
      md += `| Severity | Rule ID | Title | Resource | Remediation |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- |\n`;

      plan.security_findings.forEach(f => {
        const sevIcon = f.severity === 'CRITICAL' ? '🔴' : f.severity === 'HIGH' ? '🟠' : f.severity === 'MEDIUM' ? '🟡' : '🔵';
        md += `| ${sevIcon} **${f.severity}** | \`${f.rule_id}\` | ${f.title} | \`${f.resource}\` | ${f.remediation} |\n`;
      });
      md += `\n`;
    }

    md += `---\n*Generated by [TofuForge](https://github.com/alexandrmotologa/tofuforge) plan visualizer and destruction guard.*\n`;
    return md;
  };

  const markdownContent = generateMarkdown();

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'tofuforge-pr-summary.md';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md">
      <div className="w-full max-w-2xl rounded-2xl bg-slate-900 border border-slate-800 shadow-2xl flex flex-col max-h-[85vh]">
        {/* Header */}
        <div className="p-4 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="p-2 rounded-lg bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-slate-100">Pull Request Markdown Report</h3>
              <p className="text-xs text-slate-400">Ready to post as automated GitHub/GitLab comment</p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold shadow-sm transition"
            >
              {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
              {copied ? 'Copied to Clipboard!' : 'Copy Markdown'}
            </button>
            <button
              onClick={handleDownload}
              className="p-1.5 rounded-lg bg-slate-800 text-slate-300 hover:text-white border border-slate-700 transition"
              title="Download markdown file"
            >
              <Download className="w-4 h-4" />
            </button>
            <button
              onClick={onClose}
              className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Markdown preview */}
        <div className="flex-1 overflow-y-auto p-4">
          <pre className="p-4 rounded-xl bg-slate-950 border border-slate-800 text-slate-300 font-mono text-xs whitespace-pre-wrap leading-relaxed select-all">
            {markdownContent}
          </pre>
        </div>
      </div>
    </div>
  );
};
